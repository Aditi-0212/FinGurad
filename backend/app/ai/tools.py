"""
Tools available to the AI investigation controller.

Core rule from the spec: the AI must never invent financial facts. Every
tool here returns data pulled directly from Postgres or the ML layer —
nothing here is generated by an LLM. The controller (controller.py) is
the only place an LLM touches this data, and only to explain/summarize
what these tools already found, never to originate a number.

Each tool function takes (db: Session, **kwargs) and returns a plain
dict (JSON-serializable) — this is what gets fed back to the model as
a tool result.
"""

from datetime import date

import pandas as pd
from sqlalchemy.orm import Session

from app.database.models import Anomaly, Budget, Receivable, Transaction, Vendor
from app.ml.duplicate_detection import find_duplicate_invoices
from app.services.analytics_service import (
    get_reference_date,
    load_receivables_df,
    load_transactions_df,
    load_vendors_df,
)


def get_transaction(db: Session, transaction_id: str) -> dict:
    txn = db.query(Transaction).filter(Transaction.transaction_id == transaction_id).first()
    if not txn:
        return {"error": f"No transaction found with id {transaction_id}"}
    return {
        "transaction_id": txn.transaction_id,
        "date": txn.date.date().isoformat(),
        "vendor_id": txn.vendor_id,
        "vendor_name": txn.vendor_name,
        "department": txn.department,
        "category": txn.category,
        "amount": txn.amount,
        "payment_method": txn.payment_method,
        "invoice_id": txn.invoice_id,
        "description": txn.description,
        "approval_status": txn.approval_status,
    }


def get_vendor_history(db: Session, vendor_id: str) -> dict:
    vendor = db.query(Vendor).filter(Vendor.vendor_id == vendor_id).first()
    if not vendor:
        return {"error": f"No vendor found with id {vendor_id}"}
    return {
        "vendor_id": vendor.vendor_id,
        "vendor_name": vendor.vendor_name,
        "vendor_age_months": vendor.vendor_age,
        "industry": vendor.industry,
        "risk_level": vendor.risk_level,
        "total_transactions": vendor.total_transactions,
        "average_transaction": vendor.average_transaction,
    }


def find_similar_invoices(db: Session, transaction_id: str) -> dict:
    """Reuses the same fuzzy-matching logic from Phase 4, scoped to one transaction."""
    txn = db.query(Transaction).filter(Transaction.transaction_id == transaction_id).first()
    if not txn:
        return {"error": f"No transaction found with id {transaction_id}"}

    tx_df = load_transactions_df(db)
    matches = find_duplicate_invoices(tx_df)
    relevant = [
        m
        for m in matches
        if m.transaction_id_a == transaction_id or m.transaction_id_b == transaction_id
    ]
    return {
        "transaction_id": transaction_id,
        "similar_invoice_count": len(relevant),
        "matches": [
            {
                "other_transaction_id": m.transaction_id_b if m.transaction_id_a == transaction_id else m.transaction_id_a,
                "similarity_score": m.combined_score,
                "amount_diff_pct": m.amount_diff_pct,
                "days_apart": m.days_apart,
                "reasons": m.reasons,
            }
            for m in relevant
        ],
    }


def get_budget_status(db: Session, department: str, month: str) -> dict:
    budget = db.query(Budget).filter(Budget.department == department, Budget.month == month).first()
    if not budget:
        return {"error": f"No budget found for {department} in {month}"}
    overrun_pct = round(max(0.0, (budget.actual_spending - budget.budget) / budget.budget * 100), 1) if budget.budget else 0.0
    return {
        "department": budget.department,
        "month": budget.month,
        "budget": budget.budget,
        "actual_spending": budget.actual_spending,
        "overrun_pct": overrun_pct,
    }


def get_customer_receivables(db: Session, customer: str) -> dict:
    records = db.query(Receivable).filter(Receivable.customer == customer).all()
    if not records:
        return {"error": f"No receivables found for customer {customer}"}
    as_of = get_reference_date(db)
    return {
        "customer": customer,
        "invoice_count": len(records),
        "invoices": [
            {
                "invoice_id": r.invoice_id,
                "amount": r.amount,
                "due_date": r.due_date.date().isoformat(),
                "payment_status": r.payment_status,
                "days_overdue": max(0, (as_of - r.due_date.date()).days) if r.payment_status != "Paid" else 0,
            }
            for r in records
        ],
    }


def get_cashflow_summary(db: Session) -> dict:
    from app.services.analytics_service import get_cashflow_forecast

    forecast = get_cashflow_forecast(db)
    return {
        "as_of_date": forecast.as_of_date,
        "current_cash_estimate": forecast.current_cash_estimate,
        "daily_net_change_trend": forecast.daily_net_change_trend,
        "projected_deficit_date": forecast.projected_deficit_date,
        "days_until_deficit": forecast.days_until_deficit,
    }


def get_related_transactions(db: Session, vendor_id: str, days: int = 30) -> dict:
    tx_df = load_transactions_df(db)
    vendor_txns = tx_df[tx_df["vendor_id"] == vendor_id].copy()
    vendor_txns["date"] = pd.to_datetime(vendor_txns["date"])
    vendor_txns = vendor_txns.sort_values("date", ascending=False).head(20)
    return {
        "vendor_id": vendor_id,
        "recent_transaction_count": len(vendor_txns),
        "transactions": [
            {
                "transaction_id": row["transaction_id"],
                "date": row["date"].date().isoformat(),
                "amount": row["amount"],
                "description": row["description"],
            }
            for _, row in vendor_txns.iterrows()
        ],
    }


def calculate_risk(db: Session, anomaly_id: int) -> dict:
    """Returns the risk score already computed by the ML layer (Phase 4) —
    the AI never invents or recalculates this number itself, only explains it."""
    anomaly = db.query(Anomaly).filter(Anomaly.id == anomaly_id).first()
    if not anomaly:
        return {"error": f"No anomaly found with id {anomaly_id}"}
    return {
        "anomaly_id": anomaly.id,
        "transaction_id": anomaly.transaction_id,
        "type": anomaly.type,
        "risk_score": anomaly.risk_score,
        "signals": anomaly.signals,
    }


def list_budget_overruns(db: Session) -> dict:
    """All department/month combos currently over budget, for questions like
    'which departments exceeded their budgets'."""
    from app.services.analytics_service import get_budget_statuses

    statuses = get_budget_statuses(db)
    overruns = [b for b in statuses if b.overrun_pct > 0]
    return {
        "overrun_count": len(overruns),
        "overruns": [
            {
                "department": b.department,
                "month": b.month,
                "budget": b.budget,
                "actual_spending": b.actual_spending,
                "overrun_pct": b.overrun_pct,
                "risk_level": b.risk_level,
            }
            for b in overruns
        ],
    }


def get_top_vendors_by_spending(db: Session, limit: int = 5) -> dict:
    """Vendors with the highest total transaction volume, for questions like
    'which vendors contributed most to spending'."""
    tx_df = load_transactions_df(db)
    top = tx_df.groupby(["vendor_id", "vendor_name"])["amount"].sum().sort_values(ascending=False).head(limit)
    return {
        "top_vendors": [
            {"vendor_id": vid, "vendor_name": name, "total_spending": round(total, 2)}
            for (vid, name), total in top.items()
        ]
    }


def list_overdue_receivables(db: Session, limit: int = 5) -> dict:
    """Highest-value overdue receivables, for questions like 'highest-value overdue receivables'."""
    from app.services.analytics_service import get_receivable_statuses

    statuses = get_receivable_statuses(db)
    overdue = sorted(
        [r for r in statuses if r.payment_status == "Overdue"],
        key=lambda r: r.amount,
        reverse=True,
    )[:limit]
    return {
        "overdue_receivables": [
            {
                "invoice_id": r.invoice_id,
                "customer": r.customer,
                "amount": r.amount,
                "days_overdue": r.days_overdue,
                "priority": r.priority,
            }
            for r in overdue
        ]
    }


def list_high_risk_transactions(db: Session, limit: int = 5) -> dict:
    """Highest risk-score open anomalies, for questions like 'which transactions have the highest risk'."""
    anomalies = db.query(Anomaly).filter(Anomaly.status == "Open").order_by(Anomaly.risk_score.desc()).limit(limit).all()
    return {
        "high_risk_transactions": [
            {
                "anomaly_id": a.id,
                "transaction_id": a.transaction_id,
                "type": a.type,
                "risk_score": a.risk_score,
                "signals": a.signals,
            }
            for a in anomalies
        ]
    }


def get_monthly_expense_trend(db: Session) -> dict:
    """Total spending per month, for questions like 'why did expenses increase this month'."""
    tx_df = load_transactions_df(db)
    tx_df["month"] = pd.to_datetime(tx_df["date"]).dt.strftime("%Y-%m")
    monthly = tx_df.groupby("month")["amount"].sum().sort_index()
    return {"monthly_spending": [{"month": m, "total": round(v, 2)} for m, v in monthly.items()]}


